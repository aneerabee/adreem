revoke all on schema adreem_private from public, anon, authenticated, service_role;

create table public.adreem_profiles (
  id uuid primary key references auth.users(id) on delete restrict,
  email text not null,
  display_name text not null default '',
  telegram_user_id bigint unique,
  language text not null default 'ar' check (language in ('ar', 'en')),
  is_system_owner boolean not null default false,
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index adreem_profiles_email_key
  on public.adreem_profiles (lower(email));

create table public.adreem_ledgers (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null unique references public.adreem_profiles(id) on delete restrict,
  legacy_ledger_id text unique,
  name text not null default 'ADREEM',
  version smallint not null default 3 check (version >= 3),
  revision bigint not null default 0 check (revision >= 0),
  reset_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, owner_id)
);

create table public.adreem_accounts (
  ledger_id uuid not null,
  owner_id uuid not null,
  record_id text not null,
  name text not null,
  account_type text not null check (account_type in ('person', 'cash', 'bank', 'expense', 'asset', 'project', 'summary', 'review')),
  value_kind text not null check (value_kind in ('cash', 'bank', 'receivable', 'expense', 'asset', 'project', 'summary', 'review')),
  currency_kind text not null check (currency_kind in ('LYD', 'USD', 'multi')),
  status text not null default 'active' check (status in ('active', 'inactive', 'needs_review')),
  balance_dinar numeric(15, 0) not null default 0,
  balance_usd numeric(15, 0) not null default 0,
  posted_count bigint not null default 0 check (posted_count >= 0),
  structure_locked boolean not null default false,
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (ledger_id, record_id),
  foreign key (ledger_id, owner_id)
    references public.adreem_ledgers(id, owner_id) on delete cascade,
  check (
    (account_type = 'person' and value_kind = 'receivable') or
    (account_type = 'cash' and value_kind = 'cash') or
    (account_type = 'bank' and value_kind = 'bank') or
    (account_type = 'expense' and value_kind = 'expense') or
    (account_type = 'asset' and value_kind = 'asset') or
    (account_type = 'project' and value_kind = 'project') or
    (account_type = 'summary' and value_kind = 'summary') or
    (account_type = 'review' and value_kind = 'review')
  ),
  check (
    value_kind not in ('cash', 'bank', 'asset') or
    (balance_dinar >= 0 and balance_usd >= 0)
  )
);

create table public.adreem_dimensions (
  ledger_id uuid not null,
  owner_id uuid not null,
  record_id text not null,
  name text not null default '',
  status text not null default 'active' check (status in ('active', 'inactive')),
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (ledger_id, record_id),
  foreign key (ledger_id, owner_id)
    references public.adreem_ledgers(id, owner_id) on delete cascade
);

create table public.adreem_movements (
  ledger_id uuid not null,
  owner_id uuid not null,
  record_id text not null,
  sequence bigint generated by default as identity,
  movement_type text not null check (movement_type in (
    'opening_balance', 'transfer', 'cash_deposit', 'cash_withdrawal',
    'expense', 'truck_expense', 'truck_income', 'usd_sale',
    'usd_purchase', 'external_income', 'correction'
  )),
  status text not null check (status in ('draft', 'needs_review', 'posted', 'voided')),
  amount numeric(15, 0),
  currency text check (currency is null or currency in ('LYD', 'USD')),
  source_account_id text,
  destination_account_id text,
  rate numeric(15, 8),
  dimension_id text,
  expense_category_id text,
  occurred_at timestamptz not null default now(),
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (ledger_id, record_id),
  unique (ledger_id, sequence),
  foreign key (ledger_id, owner_id)
    references public.adreem_ledgers(id, owner_id) on delete cascade,
  foreign key (ledger_id, source_account_id)
    references public.adreem_accounts(ledger_id, record_id) deferrable initially deferred,
  foreign key (ledger_id, destination_account_id)
    references public.adreem_accounts(ledger_id, record_id) deferrable initially deferred,
  foreign key (ledger_id, dimension_id)
    references public.adreem_dimensions(ledger_id, record_id) deferrable initially deferred,
  foreign key (ledger_id, expense_category_id)
    references public.adreem_accounts(ledger_id, record_id) deferrable initially deferred,
  check (status <> 'posted' or (amount is not null and amount <> 0 and currency is not null)),
  check (rate is null or rate > 0)
);

