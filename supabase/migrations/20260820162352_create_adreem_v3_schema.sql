create or replace function public.adreem_normalize_search_text(p_value text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select lower(btrim(regexp_replace(
    translate(
      regexp_replace(normalize(coalesce(p_value, ''), NFKC), '[ؐ-ًؚ-ٰٟۖ-ۭـ]', '', 'g'),
      'أإآى',
      'اااي'
    ),
    '\s+',
    ' ',
    'g'
  )));
$$;

