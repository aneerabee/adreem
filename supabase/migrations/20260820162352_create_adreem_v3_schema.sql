create or replace function public.adreem_current_owner_is_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.adreem_profiles as profile
    where profile.id = (select auth.uid())
      and profile.is_active
      and lower(coalesce((select auth.jwt()) -> 'app_metadata' ->> 'adreem_member', 'false')) = 'true'
  );
$$;

