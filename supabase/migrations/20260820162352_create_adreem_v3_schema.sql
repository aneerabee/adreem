create table public.adreem_attachments (
  ledger_id uuid not null,
  owner_id uuid not null,
  record_id text not null,
  movement_id text,
  account_id text,
  storage_path text,
  file_name text not null default '',
  mime_type text not null default 'application/octet-stream',
  size_bytes bigint not null default 0 check (size_bytes >= 0),
  hidden_at timestamptz,
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (ledger_id, record_id),
  unique (ledger_id, storage_path),
  foreign key (ledger_id, owner_id)
    references public.adreem_ledgers(id, owner_id) on delete cascade,
  foreign key (ledger_id, movement_id)
    references public.adreem_movements(ledger_id, record_id) on delete cascade,
  foreign key (ledger_id, account_id)
    references public.adreem_accounts(ledger_id, record_id) on delete cascade,
  check (movement_id is not null or account_id is not null),
  check (storage_path is not null),
  check (nullif(payload ->> 'url', '') is null or nullif(payload ->> 'url', '') ~ '^https://'),
  check (
    storage_path is null or (
      storage_path like owner_id::text || '/' || ledger_id::text || '/_%' and
      storage_path not like '%..%'
    )
  )
);

